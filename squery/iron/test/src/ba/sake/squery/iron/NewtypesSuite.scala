package ba.sake.squery.iron

import java.sql.DriverManager
import java.util.UUID
import scala.compiletime.testing.typeChecks
import scala.util.Using
import ba.sake.squery.{*, given}
import ba.sake.squery.iron.given

class NewtypesSuite extends munit.FunSuite:
  for database <- Seq("h2", "sqlite") do
    test(s"$database: JDBC exposes referenced columns and composite FK order") {
      withConnection(database) {
        sql"CREATE TABLE parent_rows(tenant_id BIGINT, id BIGINT, PRIMARY KEY(tenant_id, id))".update()
        sql"""CREATE TABLE child_rows(tenant_id BIGINT, parent_id BIGINT,
          FOREIGN KEY(tenant_id, parent_id) REFERENCES parent_rows(tenant_id, id))""".update()
        val schema = if database == "h2" then "PUBLIC" else "main"
        val table = if database == "h2" then "CHILD_ROWS" else "child_rows"
        val metadata = summon[SqueryConnection].underlying.getMetaData
        Using.resource(metadata.getImportedKeys(null, schema, table)) { rs =>
          val columns = scala.collection.mutable.ArrayBuffer.empty[(Int, String, String, String)]
          while rs.next() do
            columns += ((
              rs.getInt("KEY_SEQ"),
              rs.getString("FKCOLUMN_NAME").toLowerCase,
              rs.getString("PKTABLE_NAME").toLowerCase,
              rs.getString("PKCOLUMN_NAME").toLowerCase
            ))
          assertEquals(
            columns.sortBy(_._1).toSeq,
            Seq((1, "tenant_id", "parent_rows", "tenant_id"), (2, "parent_id", "parent_rows", "id"))
          )
        }
      }
    }

    test(s"$database: typed PKs, FK rows, nullable FKs, generated keys and IN queries") {
      withConnection(database) {
        val idDefinition = if database == "h2" then "BIGINT GENERATED BY DEFAULT AS IDENTITY" else "INTEGER"
        Query(s"CREATE TABLE users(id $idDefinition PRIMARY KEY, name VARCHAR NOT NULL)", Seq.empty).update()
        sql"""CREATE TABLE orders(id BIGINT PRIMARY KEY,
          user_id BIGINT NOT NULL REFERENCES users(id), reviewer_id BIGINT REFERENCES users(id))""".update()
        val userId = sql"INSERT INTO users(name) VALUES ('Alice')".insertReturningGenKeys[UserRow.PK]().head
        assertEquals(userId, UserRow.PK(1L))
        val user = UserRow(userId, "Alice")
        assertEquals(sql"SELECT id, name FROM users".readRow[UserRow](), user)

        val order = OrderRow(OrderRow.PK(10L), userId, Some(userId))
        sql"INSERT INTO orders VALUES (${order.id}, ${order.user_id}, ${order.reviewer_id})".update()
        val absent: Option[UserRow.PK] = None
        sql"INSERT INTO orders VALUES (${OrderRow.PK(11L)}, $userId, $absent)".update()
        assertEquals(
          sql"SELECT id, user_id, reviewer_id FROM orders ORDER BY id".readRows[OrderRow](),
          Seq(order, OrderRow(OrderRow.PK(11L), userId, None))
        )
        assertEquals(
          sql"SELECT id FROM users WHERE id IN ${Query.in(Seq(userId))}".readValues[UserRow.PK](),
          Seq(userId)
        )
        assertEquals(
          sql"SELECT reviewer_id FROM orders WHERE id = ${OrderRow.PK(11L)}".readValue[Option[UserRow.PK]](),
          None
        )
      }
    }

    test(s"$database: generic String newtype, optional values and runtime construction") {
      withConnection(database) {
        val text = java.lang.System.getProperty("java.version")
        val label = Label(text)
        assertEquals(sql"SELECT $label".readValue[Label](), label)
        assertEquals(sql"SELECT ${Some(label)}".readValue[Option[Label]](), Some(label))
        assertEquals(sql"SELECT ${Option.empty[Label]}".readValue[Option[Label]](), None)
      }
    }

    test(s"$database: constrained newtype validates database values by index and by name") {
      withConnection(database) {
        assertEquals(sql"SELECT 5".readValue[Quantity](), Quantity(5))
        assertEquals(sql"SELECT ${Quantity(7)}".readValue[Quantity](), Quantity(7))
        intercept[IllegalArgumentException](sql"SELECT -1".readValue[Quantity]())
        intercept[IllegalArgumentException](sql"SELECT -1".readValue[Option[Quantity]]())
        val read = summon[SqlRead[Quantity]]
        Using.resource(summon[SqueryConnection].underlying.createStatement()) { stmt =>
          Using.resource(stmt.executeQuery("SELECT -1 AS quantity")) { rs =>
            assert(rs.next())
            intercept[IllegalArgumentException](read.readByName(rs, "quantity"))
          }
        }
      }
    }

  test("H2: UUID newtype reuses database-specific codecs") {
    import ba.sake.squery.h2.given
    withConnection("h2") {
      val token = Token(UUID.randomUUID())
      assertEquals(sql"SELECT $token".readValue[Token](), token)
    }
  }

  test("H2: arrays of unconstrained IDs reuse SQL type names") {
    import ba.sake.squery.write.given
    withConnection("h2") {
      val ids = Vector(UserRow.PK(1L), UserRow.PK(2L))
      assertEquals(sql"SELECT $ids".readValue[Vector[UserRow.PK]](), ids)
    }
  }

  test("correct PK/FK construction and typed lookup compile") {
    assert(typeChecks("""import ba.sake.squery.iron.*
      val user = UserRow(UserRow.PK(1L), "Alice")
      val order = OrderRow(OrderRow.PK(2L), user.id, Some(user.id))
      def findUser(id: UserRow.PK) = id
      findUser(order.user_id)
    """))
  }

  test("different PKs, FK assignments and raw primitives cannot be mixed") {
    assert(!typeChecks("""import ba.sake.squery.iron.*; val id: UserRow.PK = OrderRow.PK(1L)"""))
    assert(!typeChecks("""import ba.sake.squery.iron.*; val id: UserRow.PK = 1L"""))
    assert(!typeChecks("""import ba.sake.squery.iron.*; OrderRow(OrderRow.PK(1L), OrderRow.PK(2L), None)"""))
    assert(
      !typeChecks("""import ba.sake.squery.iron.*; OrderRow(OrderRow.PK(1L), UserRow.PK(2L), Some(OrderRow.PK(3L)))""")
    )
    assert(!typeChecks("""import ba.sake.squery.iron.*
      def findUser(id: UserRow.PK) = id
      findUser(OrderRow.PK(1L))
    """))
  }

  private def withConnection(database: String)(body: SqueryConnection ?=> Unit): Unit =
    Class.forName(if database == "h2" then "org.h2.Driver" else "org.sqlite.JDBC")
    val url = if database == "h2" then "jdbc:h2:mem:" else "jdbc:sqlite::memory:"
    Using.resource(DriverManager.getConnection(url)) { conn =>
      body(using SqueryConnection(conn, lintUpdates = false))
    }
